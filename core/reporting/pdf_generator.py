SUCCESS_COLOR = colors.HexColor("#10B981")    # Emerald Green
WARNING_COLOR = colors.HexColor("#F59E0B")    # Amber


class NumberedCanvas(canvas.Canvas):
    """Custom canvas that tracks total pages to render 'Page X of Y' footers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(MUTED_TEXT)

        # Running Header (pages > 1)
        if self._pageNumber > 1:
            self.drawString(40, A4[1] - 30, "Resume Intelligence Platform — ATS Audit & Classification Report")
            self.setStrokeColor(BORDER_COLOR)
            self.setLineWidth(0.5)
            self.line(40, A4[1] - 35, A4[0] - 40, A4[1] - 35)

        # Running Footer
        footer_text = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(A4[0] - 40, 25, footer_text)
        self.drawString(40, 25, "Confidential — Generated by Resume Intelligence System (Academic Demonstration)")
        self.setStrokeColor(BORDER_COLOR)
        self.setLineWidth(0.5)
        self.line(40, 35, A4[0] - 40, 35)

        self.restoreState()


class PDFReportGenerator:
    """Generates comprehensive PDF reports from resume analysis results."""

    def __init__(self):
        self.styles = getSampleStyleSheet()
        self._init_custom_styles()

    def _init_custom_styles(self):
        """Define tailored typography styles."""
        self.styles.add(ParagraphStyle(
            "DocTitle",
            parent=self.styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=20,
            leading=24,
            textColor=PRIMARY_COLOR,
            spaceAfter=4,
        ))
        self.styles.add(ParagraphStyle(
            "DocSubtitle",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=10,
            leading=13,
            textColor=MUTED_TEXT,
            spaceAfter=12,
        ))
        self.styles.add(ParagraphStyle(
            "SectionHeader",
            parent=self.styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=12,
            leading=16,
            textColor=PRIMARY_COLOR,
            spaceBefore=10,
            spaceAfter=6,
        ))
        self.styles.add(ParagraphStyle(
            "BodyDark",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=9,
            leading=13,
            textColor=DARK_TEXT,
        ))
        self.styles.add(ParagraphStyle(
            "BodyMuted",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=8,
            leading=11,
            textColor=MUTED_TEXT,
        ))
        self.styles.add(ParagraphStyle(
            "TableCell",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11,
            textColor=DARK_TEXT,
        ))
        self.styles.add(ParagraphStyle(
            "TableCellBold",
            parent=self.styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=8.5,
            leading=11,
            textColor=PRIMARY_COLOR,
        ))
        self.styles.add(ParagraphStyle(
            "CardTitle",
            parent=self.styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=9.5,
            leading=13,
            textColor=PRIMARY_COLOR,
        ))
        self.styles.add(ParagraphStyle(
            "ScoreBig",
            parent=self.styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=26,
            leading=30,
            textColor=SECONDARY_COLOR,
            alignment=1,  # Center
        ))
        self.styles.add(ParagraphStyle(
            "ScoreLabel",
            parent=self.styles["Normal"],
            fontName="Helvetica",
            fontSize=8.5,
            leading=11,
            textColor=MUTED_TEXT,
            alignment=1,
        ))

    def generate_report(self, analysis_data: dict, output_path: Path | str | None = None) -> bytes:
        """
        Build and return the PDF binary buffer.
        If output_path is provided, also saves to that location.
        """
        buffer = BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=40,
            rightMargin=40,
            topMargin=45,
            bottomMargin=45,
        )

        story = []

        # --- 1. Header Banner & Identity ---
        story.append(Paragraph("RESUME INTELLIGENCE PLATFORM", self.styles["DocTitle"]))
        story.append(Paragraph("NLP Classification, ATS Quality Scoring & Analytical Profile Audit", self.styles["DocSubtitle"]))
        story.append(HRFlowable(width="100%", thickness=1.5, color=SECONDARY_COLOR, spaceAfter=12))

        # --- 2. Metadata & Summary Card ---
        now_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        report_id = f"RIR-{analysis_data.get('id', 'NEW')}-{datetime.now().strftime('%Y%m%d%H%M')}"
        meta_data = [
            [
                Paragraph("<b>Report ID:</b>", self.styles["TableCellBold"]),
                Paragraph(report_id, self.styles["TableCell"]),
                Paragraph("<b>Date / Time:</b>", self.styles["TableCellBold"]),
                Paragraph(str(analysis_data.get("created_at", now_str))[:19], self.styles["TableCell"]),
            ],
            [
                Paragraph("<b>Filename:</b>", self.styles["TableCellBold"]),
                Paragraph(str(analysis_data.get("filename", "Uploaded Resume")), self.styles["TableCell"]),
                Paragraph("<b>Format / Engine:</b>", self.styles["TableCellBold"]),
                Paragraph(f"{analysis_data.get('file_format', 'PDF')} ({analysis_data.get('extraction_method', 'Digital')})", self.styles["TableCell"]),
            ],
            [
                Paragraph("<b>Document Scope:</b>", self.styles["TableCellBold"]),
                Paragraph(f"{analysis_data.get('word_count', 0)} words, {analysis_data.get('page_count', 1)} page(s)", self.styles["TableCell"]),
                Paragraph("<b>OCR Applied:</b>", self.styles["TableCellBold"]),
                Paragraph("Yes (Scanned Doc)" if analysis_data.get("ocr_used") else "No (Digital Text)", self.styles["TableCell"]),
            ],
        ]
        meta_table = Table(meta_data, colWidths=[90, 165, 90, 170])
        meta_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
            ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]))
        story.append(meta_table)
        story.append(Spacer(1, 14))

        # --- 3. Primary Classification & ATS Score Box (2 Columns) ---
        cat = analysis_data.get("predicted_category", "Unclassified")
        conf = analysis_data.get("confidence", 0.0)
        score = analysis_data.get("ats_score", 0.0)
        grade = analysis_data.get("ats_grade", "Needs Improvement")

        col1_content = [
            Paragraph("<b>Predicted Domain Category</b>", self.styles["CardTitle"]),
            Spacer(1, 4),
            Paragraph(f"<font size=14 color='{PRIMARY_COLOR.hexval()}'><b>{cat}</b></font>", self.styles["Normal"]),
            Spacer(1, 4),
            Paragraph(f"Confidence: <b>{conf * 100:.1f}%</b> ({analysis_data.get('score_type', 'Calibrated Probability')})", self.styles["TableCell"]),
            Paragraph(f"Model: {analysis_data.get('model_name', 'Linear Support Vector Classifier')}", self.styles["BodyMuted"]),
        ]

        # Alternative predictions
        alts = analysis_data.get("alternative_predictions") or []
        if alts:
            col1_content.append(Spacer(1, 4))
            col1_content.append(Paragraph("<b>Alternative Class Candidates:</b>", self.styles["TableCellBold"]))
            for alt in alts[:2]:
                if isinstance(alt, dict):
                    alt_name = alt.get("category", "")
                    alt_pct = alt.get("percentage", 0.0)
                else:
                    alt_name = getattr(alt, "category", str(alt))
                    alt_pct = getattr(alt, "percentage", 0.0)
                col1_content.append(Paragraph(f"• {alt_name}: {alt_pct:.1f}%", self.styles["BodyMuted"]))

        col2_content = [
            Paragraph("<b>ATS Resume Quality Score</b>", self.styles["CardTitle"]),
            Spacer(1, 2),
            Paragraph(f"{score:.0f}", self.styles["ScoreBig"]),
            Paragraph(f"<b>Grade: {grade}</b>", self.styles["ScoreLabel"]),
            Paragraph("Scale: 0 to 100 (Industry Standard Formula)", self.styles["BodyMuted"]),
        ]

        hero_table = Table([[col1_content, col2_content]], colWidths=[315, 200])
        hero_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (0, 0), LIGHT_BG),
            ("BACKGROUND", (1, 0), (1, 0), colors.HexColor("#F0FDF4") if score >= 75 else LIGHT_BG),
            ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("TOPPADDING", (0, 0), (-1, -1), 8),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ]))
        story.append(hero_table)
        story.append(Spacer(1, 14))

        # --- 4. ATS Score Breakdown Table ---
        story.append(Paragraph("ATS Quality Score Breakdown", self.styles["SectionHeader"]))
        breakdown = analysis_data.get("score_breakdown") or {}
        if hasattr(breakdown, "to_dict"):
            breakdown_dict = breakdown.to_dict()
        elif isinstance(breakdown, dict):
            breakdown_dict = breakdown
        else:
            breakdown_dict = {}

        breakdown_rows = [
            [Paragraph("<b>Evaluation Dimension</b>", self.styles["TableCellBold"]), Paragraph("<b>Awarded Points</b>", self.styles["TableCellBold"])]
        ]
        for k, v in breakdown_dict.items():
            breakdown_rows.append([
                Paragraph(k, self.styles["TableCell"]),
                Paragraph(f"<b>{v}</b> pts", self.styles["TableCellBold"]),
            ])

        b_table = Table(breakdown_rows, colWidths=[360, 155])
        b_table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), LIGHT_BG),
            ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
            ("TOPPADDING", (0, 0), (-1, -1), 3),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
        ]))
        story.append(b_table)
        story.append(Spacer(1, 14))

        # --- 5. Extracted Technical Skills by Taxonomy ---
        story.append(Paragraph("Detected Technical Skills & Competencies", self.styles["SectionHeader"]))
        skills_data = analysis_data.get("skills_detected") or {}
        by_cat = skills_data.get("skills_by_category") or {}

        if by_cat:
            skill_rows = [[Paragraph("<b>Category</b>", self.styles["TableCellBold"]), Paragraph("<b>Matched Skills</b>", self.styles["TableCellBold"])]]
            for cat_name, skill_list in by_cat.items():
                skill_rows.append([
                    Paragraph(f"<b>{cat_name}</b>", self.styles["TableCell"]),
                    Paragraph(", ".join(skill_list), self.styles["TableCell"]),
                ])
            s_table = Table(skill_rows, colWidths=[150, 365])
            s_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, 0), LIGHT_BG),
                ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(s_table)
        else:
            story.append(Paragraph("No structured technical skills detected from the taxonomy.", self.styles["TableCell"]))

        story.append(Spacer(1, 14))

        # --- 6. Section Coverage Audit ---
        sections = analysis_data.get("section_coverage") or {}
        if sections:
            story.append(Paragraph("Resume Section Coverage Audit", self.styles["SectionHeader"]))
            sec_items = []
            for sec_name, present in sections.items():
                status_icon = "<b>[PRESENT]</b>" if present else "<font color='#DC2626'><b>[MISSING]</b></font>"
                sec_items.append(Paragraph(f"{status_icon} {sec_name.title()}", self.styles["TableCell"]))

            # Group into 2 columns
            half = (len(sec_items) + 1) // 2
            col_a = sec_items[:half]
            col_b = sec_items[half:]
            # Balance rows
            while len(col_b) < len(col_a):
                col_b.append(Paragraph("", self.styles["TableCell"]))

            sec_table_data = [[col_a[i], col_b[i]] for i in range(len(col_a))]
            sec_table = Table(sec_table_data, colWidths=[257, 258])
            sec_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
                ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("TOPPADDING", (0, 0), (-1, -1), 3),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
            ]))
            story.append(sec_table)
            story.append(Spacer(1, 14))

        # --- 7. Actionable Recommendations ---
        recs = analysis_data.get("recommendations") or []
        if recs:
            story.append(Paragraph("Actionable Improvement Recommendations", self.styles["SectionHeader"]))
            for r in recs[:6]:
                story.append(Paragraph(f"• {r}", self.styles["TableCell"]))
                story.append(Spacer(1, 2))
            story.append(Spacer(1, 12))

        # --- 8. Optional Job Match Studio Results (if present) ---
        job_score = analysis_data.get("job_match_score")
        if job_score is not None:
            story.append(Paragraph("Job Description Alignment Audit", self.styles["SectionHeader"]))
            job_details = analysis_data.get("job_match_details") or {}
            jm_rows = [
                [
                    Paragraph("<b>Job Match Score:</b>", self.styles["TableCellBold"]),
                    Paragraph(f"<b>{job_score:.1f}%</b> ({job_details.get('grade', 'Match')})", self.styles["TableCellBold"]),
                    Paragraph("<b>Skill Coverage:</b>", self.styles["TableCellBold"]),
                    Paragraph(f"{job_details.get('skill_coverage_percentage', 0.0)}%", self.styles["TableCell"]),
                ],
                [
                    Paragraph("<b>Semantic Cosine Sim:</b>", self.styles["TableCellBold"]),
                    Paragraph(f"{job_details.get('semantic_similarity_percentage', 0.0)}%", self.styles["TableCell"]),
                    Paragraph("<b>Vocabulary Overlap:</b>", self.styles["TableCellBold"]),
                    Paragraph(f"{job_details.get('keyword_overlap_percentage', 0.0)}%", self.styles["TableCell"]),
                ]
            ]
            jm_table = Table(jm_rows, colWidths=[120, 137, 120, 138])
            jm_table.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), LIGHT_BG),
                ("BOX", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, BORDER_COLOR),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]))
            story.append(jm_table)

            matched_s = job_details.get("matched_skills") or []
            missing_s = job_details.get("missing_skills") or []
            if matched_s:
                story.append(Spacer(1, 4))
                story.append(Paragraph(f"<b>Matched Skills ({len(matched_s)}):</b> {', '.join(matched_s)}", self.styles["TableCell"]))
            if missing_s:
                story.append(Spacer(1, 2))
                story.append(Paragraph(f"<font color='#DC2626'><b>Missing Target Skills ({len(missing_s)}):</b></font> {', '.join(missing_s[:10])}", self.styles["TableCell"]))
            story.append(Spacer(1, 14))

        # --- 9. Disclaimers & Methodology ---
        story.append(KeepTogether([
            Paragraph("Methodology, Limitations & Privacy Notice", self.styles["SectionHeader"]),
            Paragraph(
                "<b>Scoring Methodology:</b> The ATS Quality Score evaluates readability, contact structure, "
                "section coverage, verified taxonomy skills, quantifiable achievements, and active phrasing. "
                "The classification prediction utilizes a calibrated Support Vector Classifier trained on standardized datasets. "
                "This platform is designed for educational analytics and resume optimization; it does not constitute an endorsement, "
                "guarantee of interview selection, or certification by commercial ATS providers.",
                self.styles["BodyMuted"]
            ),
            Spacer(1, 4),
            Paragraph(
                "<b>Privacy Notice:</b> Resumes analyzed on this platform are processed locally within the sandbox environment. "
                "Raw document text is not transmitted to third-party APIs. User profile data is stored in a private local SQLite database.",
                self.styles["BodyMuted"]
            )
        ]))

        doc.build(story, canvasmaker=NumberedCanvas)
        pdf_bytes = buffer.getvalue()
        buffer.close()

        if output_path:
            out_p = Path(output_path)
            out_p.parent.mkdir(parents=True, exist_ok=True)
            with open(out_p, "wb") as f:
                f.write(pdf_bytes)

        return pdf_bytes


